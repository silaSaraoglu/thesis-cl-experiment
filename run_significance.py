"""Significance tests between models, from a finished experiment's results.

Every model in an experiment saw the same task-order configs, so each config is a
matched block (dependent sampling) and two views of the same comparison are produced,
both from shared/stats_tests.py:

  * pairwise, directional -- an exact one-sided paired permutation test per model pair,
    Holm-corrected, answering "does A outperform B?" on the metric values themselves;
  * omnibus + post-hoc -- Friedman across all models at once, and if it rejects, the
    Nemenyi post-hoc summarized as a Critical Difference diagram, on ranks.

Nothing is re-trained -- this only reads the per-config metric values already
serialized by run_experiment.py:

    python run_significance.py results/single_head/experiment_20260810_155645
    python run_significance.py results/multi_head/experiment_20260801_154816 --alpha 0.01

Writes <exp_dir>/significance/<dataset>_<metric>_* : the pairwise p-values and win
matrix as CSV, a LaTeX table, the Friedman/Nemenyi numbers, and the CD diagram.
"""

import argparse
import csv
import glob
import json
import os
import sys
from collections import defaultdict

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from shared.stats_tests import ALPHA, friedman_test, nemenyi_cd, pairwise_one_sided


def _config_order(keys):
    """config_1, config_2, ... config_10 -- numerically, not lexicographically."""
    return sorted(keys, key=lambda k: int(k.rsplit("_", 1)[1]))


def _label(result):
    """'ESN-EWC-SH-HHAR' -> 'ESN-EWC': the dataset and head are fixed per table."""
    label = result.get("model") or result.get("model_id", "?")
    suffix = "-" + result.get("dataset", "").replace("_", "-").upper()
    if suffix != "-" and label.upper().endswith(suffix):
        label = label[:-len(suffix)]
    for head in ("-SH", "-MH"):
        if label.upper().endswith(head):
            label = label[:-len(head)]
    return label


def load_experiment(exp_dir, metric):
    """dataset -> {model label -> per-config metric values}, in a shared config order."""
    by_dataset = defaultdict(dict)
    config_keys = {}

    for path in sorted(glob.glob(os.path.join(exp_dir, "*.json"))):
        with open(path) as f:
            result = json.load(f)
        per_config = result.get("per_config")
        if not per_config:  # summary.json and anything else without per-config detail
            continue

        dataset = result.get("dataset", "unknown")
        keys = _config_order(per_config)
        seen = config_keys.setdefault(dataset, keys)
        if keys != seen:
            sys.exit("%s has configs %s but other models in %s have %s -- the paired "
                     "test needs every model run on the same configs"
                     % (os.path.basename(path), keys, dataset, seen))

        values = []
        for key in keys:
            summary = per_config[key].get("summary", {})
            if metric not in summary:
                sys.exit("%s config %s has no %r (available: %s)"
                         % (os.path.basename(path), key, metric, sorted(summary)))
            values.append(summary[metric])
        by_dataset[dataset][_label(result)] = values

    if not by_dataset:
        sys.exit("no per-config results found in %s" % exp_dir)
    return by_dataset


def _mark(record, alpha):
    if record["p_holm"] < alpha:
        return "**"
    if record["p_value"] < alpha:
        return "*"
    return ""


def write_pvalues(records, path):
    fields = ["model_a", "model_b", "mean_a", "mean_b", "mean_diff", "wins", "ties",
              "n", "p_value", "p_holm", "significant_raw", "significant_holm", "exact"]
    with open(path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields, extrasaction="ignore")
        writer.writeheader()
        for record in sorted(records, key=lambda r: r["p_value"]):
            writer.writerow(record)


def write_matrix(records, models, path, alpha):
    marks = {(r["model_a"], r["model_b"]): _mark(r, alpha) for r in records}
    with open(path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["beats ->"] + models)
        for a in models:
            writer.writerow([a] + ["--" if a == b else marks[(a, b)] for b in models])


def write_tex(records, models, path, dataset, metric, alpha, head):
    marks = {(r["model_a"], r["model_b"]): _mark(r, alpha) for r in records}
    cell = {"": "", "*": r"$\checkmark$", "**": r"$\checkmark\checkmark$"}
    tag = "%s-%s-%s" % (head, dataset, metric)

    lines = [
        r"% generated by run_significance.py -- do not edit by hand",
        r"\begin{table}[htbp]",
        r"  \centering",
        r"  \caption{Pairwise one-sided paired permutation tests on %s (%s, %s, "
        r"$n=%d$ task-order configurations). A mark in row $A$, column $B$ means $A$ "
        r"significantly outperforms $B$ at $\alpha=%g$: $\checkmark$ uncorrected, "
        r"$\checkmark\checkmark$ after Holm correction across all pairwise tests.}"
        % (metric.replace("_", " "), head.replace("_", "-"), dataset.replace("_", "-"),
           records[0]["n"], alpha),
        r"  \label{tab:sig-%s}" % tag.replace("_", "-"),
        r"  \begin{tabular}{l%s}" % ("c" * len(models)),
        r"    \toprule",
        r"    & " + " & ".join(m.replace("_", r"\_") for m in models) + r" \\",
        r"    \midrule",
    ]
    for a in models:
        row = [("--" if a == b else cell[marks[(a, b)]]) for b in models]
        lines.append(r"    %s & %s \\" % (a.replace("_", r"\_"), " & ".join(row)))
    lines += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}", ""]

    with open(path, "w") as f:
        f.write("\n".join(lines))


def run_friedman_nemenyi(values, models, stem, dataset, metric, alpha, head, plot=True):
    """Friedman omnibus over the configs, then Nemenyi + CD diagram if it rejects.

    Returns the Friedman result dict with the Nemenyi Critical Difference attached.
    """
    matrix = np.array([[values[m][i] for m in models]
                       for i in range(len(values[models[0]]))])
    result = friedman_test(matrix)
    cd = nemenyi_cd(result["k_models"], result["n_blocks"], alpha)
    result["critical_difference"] = cd

    ranks = result["average_ranks"]
    order = np.argsort(ranks)                      # best (lowest) average rank first
    ranked = [models[i] for i in order]
    ranked_values = [float(ranks[i]) for i in order]

    with open(stem + "_friedman_nemenyi.csv", "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow(["friedman_statistic", "%.6f" % result["statistic"]])
        writer.writerow(["df", result["df"]])
        writer.writerow(["p_value", "%.6g" % result["p_value"]])
        writer.writerow(["n_blocks", result["n_blocks"]])
        writer.writerow(["k_models", result["k_models"]])
        writer.writerow(["alpha", alpha])
        writer.writerow(["nemenyi_critical_difference", "%.4f" % cd])
        writer.writerow([])
        writer.writerow(["model", "average_rank", "mean_" + metric])
        for name, rank in zip(ranked, ranked_values):
            writer.writerow([name, "%.4f" % rank,
                             "%.6f" % (sum(values[name]) / len(values[name]))])

    print("\n  Friedman: chi2(%d) = %.3f, p = %.4g   (n = %d configs, k = %d models)"
          % (result["df"], result["statistic"], result["p_value"],
             result["n_blocks"], result["k_models"]))
    if result["p_value"] >= alpha:
        print("  -> does not reject at alpha = %g; Nemenyi post-hoc not warranted"
              % alpha)
        return result

    print("  -> rejects at alpha = %g; Nemenyi CD = %.3f rank positions" % (alpha, cd))
    width = max(len(m) for m in ranked)
    for name, rank in zip(ranked, ranked_values):
        print("    %-*s  avg rank %.2f" % (width, name, rank))

    if plot:
        from shared.cd_diagram import plot_cd_diagram
        plot_cd_diagram(
            ranked, ranked_values, cd, stem + "_cd_diagram.png",
            title="%s -- %s (%s)" % (dataset.replace("_", "-"),
                                     metric.replace("_", " "),
                                     head.replace("_", "-")),
            alpha=alpha)
    return result


def print_report(records, models, values, dataset, metric, alpha):
    width = max(len(m) for m in models)
    print("\n%s -- %s (n=%d configs)" % (dataset, metric, records[0]["n"]))
    print("  mean %s per model:" % metric)
    for model in models:
        mean = sum(values[model]) / len(values[model])
        print("    %-*s  %.4f" % (width, model, mean))

    marks = {(r["model_a"], r["model_b"]): _mark(r, alpha) for r in records}
    header = "  %-*s | %s" % (width, "beats ->", " ".join(m[:7].center(7) for m in models))
    print("\n" + header)
    print("  " + "-" * (len(header) - 2))
    for a in models:
        cells = [("  --   " if a == b else marks[(a, b)].center(7)) for b in models]
        print("  %-*s | %s" % (width, a, " ".join(cells)))
    print("\n  * p < %g uncorrected      ** also significant after Holm correction"
          % alpha)

    print("\n  wins (row model significantly better, Holm-corrected):")
    for model in models:
        beaten = [r["model_b"] for r in records
                  if r["model_a"] == model and r["significant_holm"]]
        print("    %-*s  %d/%d" % (width, model, len(beaten), len(models) - 1))


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("exp_dir", help="experiment directory holding the result JSONs")
    parser.add_argument("--metric", default="final_accuracy",
                        help="key inside per_config[...]['summary'] (default: %(default)s)")
    parser.add_argument("--alpha", type=float, default=ALPHA,
                        help="significance level (default: %(default)s)")
    parser.add_argument("--out", default=None,
                        help="output directory (default: <exp_dir>/significance)")
    parser.add_argument("--no-plot", action="store_true",
                        help="skip the Nemenyi CD diagram, write the numbers only")
    args = parser.parse_args()

    if not os.path.isdir(args.exp_dir):
        sys.exit("no such directory: %s" % args.exp_dir)
    head = "multi_head" if "multi_head" in os.path.normpath(
        os.path.abspath(args.exp_dir)).split(os.sep) else "single_head"
    out_dir = args.out or os.path.join(args.exp_dir, "significance")
    os.makedirs(out_dir, exist_ok=True)

    for dataset, values in load_experiment(args.exp_dir, args.metric).items():
        if len(values) < 2:
            print("skipping %s: only %d model(s)" % (dataset, len(values)))
            continue

        # Ranking the models by mean first makes the win matrix read near-triangular.
        models = sorted(values, key=lambda m: -sum(values[m]) / len(values[m]))
        ordered = {m: values[m] for m in models}
        records = pairwise_one_sided(ordered, alpha=args.alpha)

        stem = os.path.join(out_dir, "%s_%s" % (dataset, args.metric))
        write_pvalues(records, stem + "_pvalues.csv")
        write_matrix(records, models, stem + "_matrix.csv", args.alpha)
        write_tex(records, models, stem + "_table.tex", dataset, args.metric,
                  args.alpha, head)
        print_report(records, models, ordered, dataset, args.metric, args.alpha)

        if len(models) >= 3:
            run_friedman_nemenyi(ordered, models, stem, dataset, args.metric,
                                 args.alpha, head, plot=not args.no_plot)
        print("\n  written to %s" % out_dir)


if __name__ == "__main__":
    main()
